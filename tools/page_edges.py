"""Records the colour at the edge of every page image.

Each printed page is a flat colour right up to its edge. The app puts that
colour behind the rounded card so iOS can draw a smooth shadow from the
card's outline, with no light or dark rim at the corners.

Writes src/data/decks/edges.ts. Run from the repository root after
tools/extract_decks.py:

    python3 tools/page_edges.py
"""

import glob
import os

from PIL import Image

OUT = "src/data/decks/edges.ts"


def edge_colour(path):
    im = Image.open(path).convert("RGB")
    w, h = im.size
    r, g, b = im.getpixel((2, h // 2))
    return "#%02X%02X%02X" % (r, g, b)


def main():
    decks = sorted(os.path.basename(d) for d in glob.glob("assets/decks/*") if os.path.isdir(d))
    lines = ["// Generated by tools/page_edges.py. Do not edit.", "", "export const pageEdges: Record<string, string[]> = {"]
    for deck in decks:
        pages = sorted(glob.glob("assets/decks/%s/page-*.webp" % deck))
        colours = ", ".join("'%s'" % edge_colour(p) for p in pages)
        lines.append("  '%s': [%s]," % (deck, colours))
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
